def _ui(label: str, group: str, control: str, order: int, enum: tuple[str, ...] = ()) -> dict:
    ui: dict[str, JsonValue] = {
        "control": control,
        "label": label,
        "tab": GROUP_LABELS.get(group, group),
        "order": order,
    }
    if enum:
        labels: dict[str, str] = {}
        for values in SELECT_LABELS.values():
            if tuple(value for value, _ in values) == enum:
                labels = dict(values)
                break
        ui["options"] = [{"value": value, "label": labels.get(value, value)} for value in enum]
    return ui


def _rationale(label: str, applies_to: str, text_override: bool = False) -> str:
    if text_override:
        return (
            f"Переопределяет «{label}» только для элемента «{ELEMENT_LABELS[applies_to]}»; "
            "без переопределения действует общий стиль текста."
        )
    return (
        f"Настраивает «{label}» для {ELEMENT_LABELS[applies_to]}; "
        "значение хранится в профиле, а не в коде генератора."
    )


def _option(
    id: str,
    group: str,
    applies_to: tuple[str, ...],
    type: OptionType,
    default: JsonValue,
    path: tuple[str, ...],
    label: str,
    *,
    order: int,
    unit: str | None = None,
    allowed_units: tuple[str, ...] = (),
    min: float | None = None,
    max: float | None = None,
    step: float | None = None,
    enum: tuple[str, ...] = (),
    depends_on: tuple[str, ...] = (),
    nullable: bool = False,
    rationale: str | None = None,
    source: str | None = None,
    test_ids: tuple[str, ...] | None = None,
    legacy: bool = True,
) -> Option:
    control = {
        "number": "number",
        "integer": "number",
        "boolean": "toggle",
        "string": "text",
        "select": "select",
        "markers": "markers",
    }[type]
    return Option(
        id=id,
        group=group,
        applies_to=applies_to,
        type=type,
        default=default,
        path=path,
        ui=_ui(label, group, control, order, enum),
        rationale=rationale or _rationale(label, applies_to[0]),
        source=source or SOURCE[group],
        unit=unit,
        allowed_units=allowed_units,
        min=min,
        max=max,
        step=step,
        enum=enum,
        depends_on=depends_on,
        nullable=nullable,
        test_ids=test_ids or TEST_IDS,
        legacy=legacy,
    )


